using System.Buffers.Binary;
using System.Text;

namespace MediaViewer.Imaging.Color;

/// <summary>色度座標（CIE xy）。</summary>
public readonly record struct Chromaticity(double X, double Y)
{
    public double[] ToXyz() => [X / Y, 1.0, (1 - X - Y) / Y];
}

/// <summary>RGB色空間の原色と白色点。</summary>
public sealed record RgbPrimaries(Chromaticity Red, Chromaticity Green, Chromaticity Blue, Chromaticity White)
{
    public static readonly Chromaticity D65 = new(0.3127, 0.3290);
    public static RgbPrimaries Srgb { get; } = new(new(0.64, 0.33), new(0.30, 0.60), new(0.15, 0.06), D65);
    public static RgbPrimaries DisplayP3 { get; } = new(new(0.680, 0.320), new(0.265, 0.690), new(0.150, 0.060), D65);
    public static RgbPrimaries Bt2020 { get; } = new(new(0.708, 0.292), new(0.170, 0.797), new(0.131, 0.046), D65);
}

/// <summary>
/// 画像に埋め込まれていない色指定（PNG の cICP / gAMA / cHRM、グレーICC など）を、
/// Direct2D の色管理へ渡せる RGB の ICC プロファイル（v2.1、行列＋トーンカーブ）として生成する。
/// </summary>
public static class IccProfileFactory
{
    private const int CurvePoints = 1024;
    private static readonly double[] D50 = [0.9642, 1.0, 0.8249];

    /// <summary>トーンカーブ（符号化値 0..1 → 線形 0..1）。</summary>
    public delegate double TransferFunction(double encoded);

    public static double SrgbToLinear(double v) => v <= 0.04045 ? v / 12.92 : Math.Pow((v + 0.055) / 1.055, 2.4);

    public static TransferFunction Gamma(double gamma) => v => Math.Pow(v, gamma);

    /// <summary>作業用の広色域RGB（BT.2020原色・ガンマ2.2）。CMYK画像の変換先に使う。</summary>
    public static byte[] WideGamutWorkingSpace { get; } = CreateRgb(RgbPrimaries.Bt2020, Gamma(2.2), "MediaViewer working space (BT.2020, gamma 2.2)");

    public static byte[] CreateRgb(RgbPrimaries primaries, TransferFunction transfer, string description)
    {
        var m = Multiply(Bradford(primaries.White.ToXyz(), D50), RgbToXyz(primaries));
        var curve = CurveTag(transfer);
        var tags = new List<(string Sig, byte[] Data)>
        {
            ("desc", TextDescription(description)),
            ("cprt", Text("Generated by MediaViewer")),
            ("wtpt", Xyz(D50)),
            ("rXYZ", Xyz([m[0, 0], m[1, 0], m[2, 0]])),
            ("gXYZ", Xyz([m[0, 1], m[1, 1], m[2, 1]])),
            ("bXYZ", Xyz([m[0, 2], m[1, 2], m[2, 2]])),
            ("rTRC", curve),
            ("gTRC", curve),
            ("bTRC", curve),
        };
        return Assemble(tags);
    }

    /// <summary>
    /// グレーのICC（kTRC）から、同じ階調特性を持つ RGB プロファイルを作る。
    /// R=G=B の値は無彩色として kTRC どおりの明るさになる。
    /// </summary>
    public static byte[]? CreateRgbFromGray(byte[] grayProfile)
    {
        if (!TryReadTag(grayProfile, "kTRC", out var trc)) return null;
        var transfer = ParseCurve(trc);
        return transfer is null ? null : CreateRgb(RgbPrimaries.Srgb, transfer, "MediaViewer RGB from gray profile");
    }

    /// <summary>ICCのデータ色空間（ヘッダーの16〜19バイト、例："RGB "、"GRAY"、"CMYK"）。</summary>
    public static string ColorSpaceOf(ReadOnlySpan<byte> icc) =>
        icc.Length >= 20 ? Encoding.ASCII.GetString(icc.Slice(16, 4)) : "";

    // ---- トーンカーブの解釈 ----

    /// <summary>ICC の curv / para タグをトーンカーブとして解釈する。対応外は null。</summary>
    public static TransferFunction? ParseCurve(ReadOnlySpan<byte> tag)
    {
        if (tag.Length < 12) return null;
        var type = Encoding.ASCII.GetString(tag[..4]);
        if (type == "curv")
        {
            var count = (int)BinaryPrimitives.ReadUInt32BigEndian(tag[8..]);
            if (count == 0) return v => v;
            if (tag.Length < 12 + count * 2) return null;
            if (count == 1) return Gamma(BinaryPrimitives.ReadUInt16BigEndian(tag[12..]) / 256.0);
            var table = new double[count];
            for (var i = 0; i < count; i++) table[i] = BinaryPrimitives.ReadUInt16BigEndian(tag[(12 + i * 2)..]) / 65535.0;
            return v =>
            {
                var pos = Math.Clamp(v, 0, 1) * (count - 1);
                var i0 = (int)Math.Floor(pos);
                var i1 = Math.Min(i0 + 1, count - 1);
                return table[i0] + (table[i1] - table[i0]) * (pos - i0);
            };
        }
        if (type == "para")
        {
            var function = BinaryPrimitives.ReadUInt16BigEndian(tag[8..]);
            int[] paramCounts = [1, 3, 4, 5, 7];
            if (function >= paramCounts.Length || tag.Length < 12 + paramCounts[function] * 4) return null;
            var p = new double[7];
            for (var i = 0; i < paramCounts[function]; i++) p[i] = BinaryPrimitives.ReadInt32BigEndian(tag[(12 + i * 4)..]) / 65536.0;
            double g = p[0], a = p[1], b = p[2], c = p[3], d = p[4], e = p[5], f = p[6];
            return function switch
            {
                0 => v => Math.Pow(v, g),
                1 => v => v >= -b / a ? Math.Pow(a * v + b, g) : 0,
                2 => v => v >= -b / a ? Math.Pow(a * v + b, g) + c : c,
                3 => v => v >= d ? Math.Pow(a * v + b, g) : c * v,
                _ => v => v >= d ? Math.Pow(a * v + b, g) + e : c * v + f,
            };
        }
        return null;
    }

    public static bool TryReadTag(ReadOnlySpan<byte> icc, string signature, out byte[] data)
    {
        data = [];
        if (icc.Length < 132) return false;
        var count = (int)BinaryPrimitives.ReadUInt32BigEndian(icc[128..]);
        if (count is <= 0 or > 200 || 132 + 12L * count > icc.Length) return false;
        for (var i = 0; i < count; i++)
        {
            var e = icc.Slice(132 + 12 * i, 12);
            if (Encoding.ASCII.GetString(e[..4]) != signature) continue;
            var offset = BinaryPrimitives.ReadUInt32BigEndian(e[4..]);
            var size = BinaryPrimitives.ReadUInt32BigEndian(e[8..]);
            if ((long)offset + size > icc.Length) return false;
            data = icc.Slice((int)offset, (int)size).ToArray();
            return true;
        }
        return false;
    }

    // ---- ICC の組み立て ----

    private static byte[] Assemble(List<(string Sig, byte[] Data)> tags)
    {
        const int headerSize = 128;
        var offset = Align(headerSize + 4 + 12 * tags.Count);
        var table = new List<(string Sig, int Offset, int Size)>();
        using var body = new MemoryStream();
        var written = new Dictionary<byte[], int>(ReferenceEqualityComparer.Instance);
        foreach (var (sig, data) in tags)
        {
            // 同じデータ（RGBのトーンカーブ等）は1か所に書いて共有する
            if (!written.TryGetValue(data, out var at))
            {
                at = offset + (int)body.Length;
                written[data] = at;
                body.Write(data);
                while (body.Length % 4 != 0) body.WriteByte(0);
            }
            table.Add((sig, at, data.Length));
        }

        var total = offset + (int)body.Length;
        var profile = new byte[total];
        var span = profile.AsSpan();
        BinaryPrimitives.WriteUInt32BigEndian(span, (uint)total);
        BinaryPrimitives.WriteUInt32BigEndian(span[8..], 0x02100000);
        Ascii(span[12..], "mntr");
        Ascii(span[16..], "RGB ");
        Ascii(span[20..], "XYZ ");
        BinaryPrimitives.WriteUInt16BigEndian(span[24..], 2026);
        BinaryPrimitives.WriteUInt16BigEndian(span[26..], 1);
        BinaryPrimitives.WriteUInt16BigEndian(span[28..], 1);
        Ascii(span[36..], "acsp");
        Ascii(span[40..], "MSFT");
        S15Fixed16(span[68..], D50[0]);
        S15Fixed16(span[72..], D50[1]);
        S15Fixed16(span[76..], D50[2]);
        BinaryPrimitives.WriteUInt32BigEndian(span[headerSize..], (uint)table.Count);
        for (var i = 0; i < table.Count; i++)
        {
            var e = span[(headerSize + 4 + 12 * i)..];
            Ascii(e, table[i].Sig);
            BinaryPrimitives.WriteUInt32BigEndian(e[4..], (uint)table[i].Offset);
            BinaryPrimitives.WriteUInt32BigEndian(e[8..], (uint)table[i].Size);
        }
        body.ToArray().CopyTo(span[offset..]);
        return profile;
    }

    private static byte[] CurveTag(TransferFunction transfer)
    {
        var b = new byte[12 + CurvePoints * 2];
        Ascii(b, "curv");
        BinaryPrimitives.WriteUInt32BigEndian(b.AsSpan(8), CurvePoints);
        for (var i = 0; i < CurvePoints; i++)
        {
            var linear = Math.Clamp(transfer(i / (double)(CurvePoints - 1)), 0, 1);
            BinaryPrimitives.WriteUInt16BigEndian(b.AsSpan(12 + i * 2), (ushort)Math.Round(linear * 65535));
        }
        return b;
    }

    private static byte[] Xyz(double[] xyz)
    {
        var b = new byte[20];
        Ascii(b, "XYZ ");
        S15Fixed16(b.AsSpan(8), xyz[0]);
        S15Fixed16(b.AsSpan(12), xyz[1]);
        S15Fixed16(b.AsSpan(16), xyz[2]);
        return b;
    }

    private static byte[] Text(string s)
    {
        var ascii = Encoding.ASCII.GetBytes(s + "\0");
        var b = new byte[8 + ascii.Length];
        Ascii(b, "text");
        ascii.CopyTo(b, 8);
        return b;
    }

    private static byte[] TextDescription(string s)
    {
        var ascii = Encoding.ASCII.GetBytes(s + "\0");
        var b = new byte[12 + ascii.Length + 4 + 4 + 2 + 1 + 67];
        Ascii(b, "desc");
        BinaryPrimitives.WriteUInt32BigEndian(b.AsSpan(8), (uint)ascii.Length);
        ascii.CopyTo(b, 12);
        return b;
    }

    private static void S15Fixed16(Span<byte> dst, double v) => BinaryPrimitives.WriteInt32BigEndian(dst, (int)Math.Round(v * 65536));

    private static void Ascii(Span<byte> dst, string s) => Encoding.ASCII.GetBytes(s).CopyTo(dst);

    private static int Align(int v) => (v + 3) & ~3;

    // ---- 行列計算 ----

    private static double[,] RgbToXyz(RgbPrimaries p)
    {
        var r = p.Red.ToXyz();
        var g = p.Green.ToXyz();
        var b = p.Blue.ToXyz();
        var m = new double[,] { { r[0], g[0], b[0] }, { r[1], g[1], b[1] }, { r[2], g[2], b[2] } };
        var k = Multiply(Invert(m), p.White.ToXyz());
        for (var row = 0; row < 3; row++)
            for (var col = 0; col < 3; col++)
                m[row, col] *= k[col];
        return m;
    }

    private static double[,] Bradford(double[] from, double[] to)
    {
        double[,] ma = { { 0.8951, 0.2664, -0.1614 }, { -0.7502, 1.7135, 0.0367 }, { 0.0389, -0.0685, 1.0296 } };
        var s = Multiply(ma, from);
        var d = Multiply(ma, to);
        var scale = new double[,] { { d[0] / s[0], 0, 0 }, { 0, d[1] / s[1], 0 }, { 0, 0, d[2] / s[2] } };
        return Multiply(Multiply(Invert(ma), scale), ma);
    }

    private static double[] Multiply(double[,] m, double[] v) =>
    [
        m[0, 0] * v[0] + m[0, 1] * v[1] + m[0, 2] * v[2],
        m[1, 0] * v[0] + m[1, 1] * v[1] + m[1, 2] * v[2],
        m[2, 0] * v[0] + m[2, 1] * v[1] + m[2, 2] * v[2],
    ];

    private static double[,] Multiply(double[,] a, double[,] b)
    {
        var r = new double[3, 3];
        for (var i = 0; i < 3; i++)
            for (var j = 0; j < 3; j++)
                r[i, j] = a[i, 0] * b[0, j] + a[i, 1] * b[1, j] + a[i, 2] * b[2, j];
        return r;
    }

    private static double[,] Invert(double[,] m)
    {
        var det = m[0, 0] * (m[1, 1] * m[2, 2] - m[1, 2] * m[2, 1])
                - m[0, 1] * (m[1, 0] * m[2, 2] - m[1, 2] * m[2, 0])
                + m[0, 2] * (m[1, 0] * m[2, 1] - m[1, 1] * m[2, 0]);
        return new double[,]
        {
            { (m[1, 1] * m[2, 2] - m[1, 2] * m[2, 1]) / det, (m[0, 2] * m[2, 1] - m[0, 1] * m[2, 2]) / det, (m[0, 1] * m[1, 2] - m[0, 2] * m[1, 1]) / det },
            { (m[1, 2] * m[2, 0] - m[1, 0] * m[2, 2]) / det, (m[0, 0] * m[2, 2] - m[0, 2] * m[2, 0]) / det, (m[0, 2] * m[1, 0] - m[0, 0] * m[1, 2]) / det },
            { (m[1, 0] * m[2, 1] - m[1, 1] * m[2, 0]) / det, (m[0, 1] * m[2, 0] - m[0, 0] * m[2, 1]) / det, (m[0, 0] * m[1, 1] - m[0, 1] * m[1, 0]) / det },
        };
    }
}
